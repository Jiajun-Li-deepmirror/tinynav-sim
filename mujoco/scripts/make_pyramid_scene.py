#!/usr/bin/env python3
"""Writes assets/mjcf/pyramid_collision.xml: the training pyramid stairs as a tinynav-sim scene (2026-11-05).

The boxes come from mjlab's own terrain generators (mjlab.terrains BoxPyramidStairsTerrainCfg /
BoxInvertedPyramidStairsTerrainCfg) with the unitree_rl_mjlab blind / depth recipe's settings: 8 m tiles, 2.0 m
platform, 0.5 m border, rises 0.05-0.18 m by difficulty, treads 0.25 (narrow) / 0.32 m (wide). Grid (x east, y north):
  row 0 (y 0..8):  inverted pyramids (a pit: walk up and out)  -- the training "stairs_up_*" tiles
  row 1 (y 8..16): pyramids (walk down from the top platform)  -- the training "stairs_down_*" tiles
  columns (x 0..32, 8 m each): rise 0.10 / 0.14 / 0.18 m at tread 0.32, then 0.18 m at tread 0.25
plus a 6 m wide ground frame around the grid (top z = 0). The output is static; this script needs an environment with
mjlab (e.g. unitree_rl_mjlab's), tinynav-sim itself does not.

  python scripts/make_pyramid_scene.py   # from mujoco/
"""
from pathlib import Path

import mujoco
import numpy as np
from mjlab.terrains import BoxInvertedPyramidStairsTerrainCfg, BoxPyramidStairsTerrainCfg

TILE = 8.0
COLUMNS = ((0.10, 0.32), (0.14, 0.32), (0.18, 0.32), (0.18, 0.25))  # (rise m, tread m)
RISE_RANGE = (0.05, 0.18)
FRAME = 6.0
OUT = Path(__file__).resolve().parents[1] / "assets" / "mjcf" / "pyramid_collision.xml"


def tile_boxes(cls, rise: float, tread: float):
  """[(pos, half, rgba)] of one mjlab tile in its own frame (origin at its corner)."""
  cfg = cls(proportion=1.0, step_height_range=RISE_RANGE, step_width=tread, platform_width=2.0, border_width=0.5,
            size=(TILE, TILE))
  difficulty = (rise - RISE_RANGE[0]) / (RISE_RANGE[1] - RISE_RANGE[0])
  spec = mujoco.MjSpec()
  spec.worldbody.add_body(name="terrain")
  out = cfg.function(difficulty, spec, np.random.default_rng(0))
  boxes = []
  for g in out.geometries:
    geom = g.geom
    assert geom.type == mujoco.mjtGeom.mjGEOM_BOX
    rgba = tuple(g.color) if g.color is not None else (0.78, 0.72, 0.60, 1.0)
    boxes.append((np.array(geom.pos, dtype=float), np.array(geom.size, dtype=float), rgba))
  return boxes


def main() -> None:
  lines = []
  for row, (cls, kind) in enumerate(((BoxInvertedPyramidStairsTerrainCfg, "pit"), (BoxPyramidStairsTerrainCfg, "top"))):
    for col, (rise, tread) in enumerate(COLUMNS):
      off = np.array([col * TILE, row * TILE, 0.0])
      for i, (pos, half, rgba) in enumerate(tile_boxes(cls, rise, tread)):
        p = pos + off
        name = f"{kind}_{int(round(rise * 100))}_{int(round(tread * 100))}_{i:02d}"
        lines.append(
          f'  <geom name="{name}" type="box" group="0" size="{half[0]:.6f} {half[1]:.6f} {half[2]:.6f}" '
          f'pos="{p[0]:.6f} {p[1]:.6f} {p[2]:.6f}" rgba="{rgba[0]:.3f} {rgba[1]:.3f} {rgba[2]:.3f} 1" '
          'contype="1" conaffinity="1" />')
  gx, gy = len(COLUMNS) * TILE, 2 * TILE
  frame = (  # (x0, x1, y0, y1): the ground around the grid, top z = 0, 0.5 m thick
    (-FRAME, gx + FRAME, -FRAME, 0.0), (-FRAME, gx + FRAME, gy, gy + FRAME),
    (-FRAME, 0.0, 0.0, gy), (gx, gx + FRAME, 0.0, gy))
  for i, (x0, x1, y0, y1) in enumerate(frame):
    lines.append(
      f'  <geom name="ground_{i}" type="box" group="0" size="{(x1 - x0) / 2:.6f} {(y1 - y0) / 2:.6f} 0.250000" '
      f'pos="{(x0 + x1) / 2:.6f} {(y0 + y1) / 2:.6f} -0.250000" rgba="0.55 0.55 0.55 1" contype="1" conaffinity="1" />')
  head = ("<!-- generated by scripts/make_pyramid_scene.py from mjlab's pyramid stairs terrains (the unitree_rl_mjlab\n"
          f"     training tiles): {len(lines)} box geoms; do not edit by hand. Included inside <worldbody> of\n"
          "     pyramid_scene.xml. -->")
  OUT.write_text(head + "\n" + "\n".join(lines) + "\n")
  print(f"wrote {OUT} ({len(lines)} boxes)")


if __name__ == "__main__":
  main()
